const assert = require('node:assert/strict');
const { before, describe, it } = require('node:test');

describe('dataset catalog', () => {
	let parseDatasetCatalog;

	before(async () => {
		({ parseDatasetCatalog } = await import('../js/dataset-catalog.mjs'));
	});

	it('parses labels, quoted descriptions, published files, and dashboard links', () => {
		assert.deepEqual(parseDatasetCatalog([
			'name,label,description,csv_public_url,parquet_public_url,dashboard_location',
			'kytc-trak-source,Source Label,"Description, with comma",https://example.com/data.csv,https://example.com/data.parquet,https://example.com/report'
		].join('\n')), [{
			id: 'kytc-trak-source',
			title: 'Source Label',
			description: 'Description, with comma',
			csvUrl: 'https://example.com/data.csv',
			parquetUrl: 'https://example.com/data.parquet',
			dashboardLocation: 'https://example.com/report'
		}]);
	});

	it('accepts sources that need Parquet generated by ETL', () => {
		assert.deepEqual(parseDatasetCatalog([
			'name,label,description,csv_public_url,parquet_public_url,dashboard_location',
			'eda_source,Source Label,Description,https://example.com/data.csv,,'
		].join('\n')), [{
			id: 'eda_source',
			title: 'Source Label',
			description: 'Description',
			csvUrl: 'https://example.com/data.csv',
			parquetUrl: null,
			dashboardLocation: null
		}]);
	});

	it('rejects duplicate names and malformed source URLs', () => {
		const header = 'name,label,description,csv_public_url,parquet_public_url,dashboard_location';
		const row = 'source,Label,Description,https://example.com/data.csv,,';
		assert.throws(
			() => parseDatasetCatalog(`${header}\n${row}\n${row}`),
			/duplicate name/
		);
		assert.throws(
			() => parseDatasetCatalog(`${header}\nsource,Label,Description,not-a-url,,`),
			/invalid CSV URL/
		);
	});
});
